EventDisplayModule::EventEntry::EventEntry(const String& ts, Event* event)
    : timestamp(ts), value(0), note(0)
{
    if (event)
    {
        eventType = formatEventType(event->getType());
        eventName = event->getName();
        value = event->getValue();
        note = event->getNote();
        
        // Beschreibung erstellen
        switch (event->getType())
        {
            case Event::Type::GATE:
                description = eventName + " (Gate: " + String(value) + ")";
                break;
            case Event::Type::NOTE:
                description = eventName + " (Note: " + String(note) + ", Vel: " + String(value) + ")";
                break;
            case Event::Type::CONTROLLER:
                description = eventName + " (CC" + String(event->getNumber()) + ": " + String(value) + ")";
                break;
            case Event::Type::PITCH:
                description = eventName + " (Pitch: " + String(value) + ")";
                break;
            case Event::Type::CLOCK:
                description = "MIDI Clock";
                break;
            case Event::Type::CLOCK_START:
                description = "MIDI Clock Start";
                break;
            case Event::Type::CLOCK_STOP:
                description = "MIDI Clock Stop";
                break;
            default:
                description = eventName;
                break;
        }
    }
}

String EventDisplayModule::formatEventType(Event::Type type)
{
    switch (type)
    {
        case Event::Type::GATE:        return "GATE";
        case Event::Type::NOTE:        return "NOTE";
        case Event::Type::CONTROLLER:  return "CC";
        case Event::Type::PITCH:       return "PITCH";
        case Event::Type::CLOCK:       return "CLK";
        case Event::Type::CLOCK_START: return "START";
        case Event::Type::CLOCK_STOP:  return "STOP";
        default:                       return "UNKNOWN";
    }
}

String EventDisplayModule::getCurrentTimeString()
{
    Time currentTime = Time::getCurrentTime();
    String s = currentTime.formatted("%H:%M:%S.") + String(currentTime.getMilliseconds() % 1000);
	return s.substring(0, 6); // Format HH:MM:SS.mmm	
}

Colour EventDisplayModule::getEventTypeColour(const String& eventType)
{
    if (eventType == "GATE")        return Colours::green;
    if (eventType == "NOTE")        return Colours::cyan;
    if (eventType == "CC")          return Colours::yellow;
    if (eventType == "PITCH")       return Colours::orange;
    if (eventType == "CLK")         return Colours::lightblue;
    if (eventType == "START")       return Colours::lime;
    if (eventType == "STOP")        return Colours::red;
    return Colours::white;
}